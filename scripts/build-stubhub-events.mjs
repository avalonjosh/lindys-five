// Regenerates lib/affiliate/stubhubEvents.ts from scripts/data/stubhub-*.txt.
// Source lines: "<eventId>|<MMDD>|<AWAY>@<HOME>[|P]" harvested from StubHub team
// pages in a browser (StubHub blocks server fetches). Season year is inferred:
// Aug-Dec => season start year, Jan-Jul => the following year.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

// StubHub venue codes that differ from NHL API abbreviations.
const NORMALIZE = { LA: 'LAK', NJ: 'NJD', TB: 'TBL', SJ: 'SJS' };
const norm = (a) => NORMALIZE[a] || a;

const files = readdirSync('scripts/data').filter((f) => /^stubhub-(nhl|mlb)-\d{4}-\d{2}\.txt$/.test(f)).sort();
const entries = new Map();
for (const f of files) {
  const [, sport, startYear] = f.match(/^stubhub-(nhl|mlb)-(\d{4})-\d{2}\.txt$/);
  for (const line of readFileSync(`scripts/data/${f}`, 'utf8').split('\n')) {
    const m = line.trim().match(/^(\d+)\|(\d{2})(\d{2})\|([A-Z]{2,3})@([A-Z]{2,3})(\|P)?$/);
    if (!m) continue;
    const [, id, mm, dd, away, home, pre] = m;
    const year = Number(mm) >= 8 ? Number(startYear) : Number(startYear) + 1;
    const key = `${sport}:${norm(home)}:${norm(away)}:${year}-${mm}-${dd}`;
    // Prefer a regular-season listing if a preseason one shares the key (never happens in practice).
    if (!entries.has(key) || !pre) entries.set(key, Number(id));
  }
}
const sorted = [...entries.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = sorted.map(([k, v]) => `  '${k}': ${v},`).join('\n');
writeFileSync('lib/affiliate/stubhubEvents.ts', `/**
 * StubHub event ids keyed by "<sport>:<HOME>:<AWAY>:<YYYY-MM-DD>" (NHL/MLB API
 * abbreviations, Eastern game date). GENERATED by scripts/build-stubhub-events.mjs
 * from scripts/data/stubhub-*.txt; do not edit by hand. Regenerate after a fresh
 * browser harvest (see the script header) when the schedule changes.
 *
 * ${sorted.length} events. Canadian home venues are not listed on StubHub US and
 * fall back to a StubHub search.
 */
export const STUBHUB_EVENT_IDS: Record<string, number> = {
${body}
};
`);
console.log(`wrote ${sorted.length} events from ${files.join(', ')}`);
